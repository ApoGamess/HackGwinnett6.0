test('documents: a user can enter an appointment without a sample clinic and keep their wording across languages', async ({ page }) => {
  await route(page, 'letter')
  await page.getByRole('button', { name: 'Enter my appointment details', exact: true }).click()
  const entry = page.getByRole('dialog', { name: 'Enter my appointment details', exact: true })
  await entry.getByRole('button', { name: 'Save visit details' }).click()
  await expect(entry.getByLabel('Clinic', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(entry.getByLabel('Date', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(entry.getByLabel('Appointment time', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(entry.getByText('Enter a valid appointment date.', { exact: true })).toBeVisible()
  await entry.getByLabel('Clinic', { exact: true }).fill('My own clinic')
  await entry.getByLabel('Date', { exact: true }).fill('2026-11-20')
  await entry.getByLabel('Appointment time', { exact: true }).fill('13:15')
  await entry.getByLabel('Address', { exact: true }).fill('My own clinic address')
  await entry.getByLabel('Arrival instructions', { exact: true }).fill('Please keep this sentence as I wrote it.')
  await entry.getByRole('button', { name: 'Save visit details' }).click()
  await expect(page.getByRole('heading', { name: 'My care', exact: true, level: 1 })).toBeVisible()
  await expect(page.locator('[role=status]')).toContainText('No booking or clinic update has been made.')
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('es')
  await route(page, 'letter')
  const details = page.getByRole('region', { name: 'Datos de mi plan de visita' })
  await expect(details).toContainText('DATOS INTRODUCIDOS POR TI')
  await expect(details).toContainText('My own clinic')
  await expect(details).toContainText('My own clinic address')
  await expect(details).toContainText('Please keep this sentence as I wrote it.')
  await expect(details).toContainText('2026-11-20')
  await expect(page.locator('#original-letter-panel')).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('en')
  await page.getByRole('button', { name: 'Edit confirmed details', exact: true }).click()
  await expect(page.getByRole('dialog').getByLabel('Date', { exact: true })).toHaveValue('2026-11-20')
  await expect(page.getByRole('dialog').getByLabel('Appointment time', { exact: true })).toHaveValue('13:15')
})
