test('discovery: search, filter indicators, honest access states and comparison cap', async ({ page }) => {
  const cards = page.locator('.provider-list article')
  await expect(cards).toHaveCount(3)
  await page.getByRole('searchbox', { name: 'Search sample clinics' }).fill('family MEDICINE')
  await expect(cards).toHaveCount(1)
  await expect(cards).toContainText('Not specified')
  await page.getByRole('searchbox').fill('no clinic here')
  await expect(page.getByRole('heading', { name: 'No matching sample clinics' })).toBeVisible()
  await page.getByRole('button', { name: 'Show all sample clinics' }).click()
  await page.getByRole('checkbox', { name: 'Written communication', exact: true }).check()
  await expect(cards).toHaveCount(2)
  await expect(page.getByRole('button', { name: 'Remove filter: Written communication' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Quiet waiting', exact: true }).check()
  await expect(cards).toHaveCount(1)
  await page.getByRole('button', { name: 'Reset search and filters' }).click()
  await expect(cards).toHaveCount(3)
  await expect(cards.filter({ hasText: 'Meadow Health Centre' })).toContainText('Not available in the fictional sample')
  await page.getByRole('checkbox', { name: 'Compare Willow Community Clinic' }).check()
  await page.getByRole('checkbox', { name: 'Compare Cedar Family Practice' }).check()
  await expect(page.getByRole('checkbox', { name: 'Compare Meadow Health Centre' })).toBeDisabled()
  const comparison = page.getByRole('region', { name: 'Compare sample clinics' })
  await expect(comparison.locator('article')).toHaveCount(2)
  await comparison.getByRole('button', { name: 'Add this to my questions: Quiet waiting · Cedar Family Practice' }).click()
  await expect(cards.filter({ hasText: 'Cedar Family Practice' }).getByRole('button', { name: 'Question added to my visit: Quiet waiting · Cedar Family Practice' })).toBeDisabled()
  await page.screenshot({ path: 'artifacts/carenori-clinic-comparison.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  const boxes = await comparison.locator('article').evaluateAll(elements => elements.map(element => ({ top: element.getBoundingClientRect().top, bottom: element.getBoundingClientRect().bottom })))
  expect(boxes[1].top).toBeGreaterThanOrEqual(boxes[0].bottom)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1)).toBe(true)
  await route(page, 'care')
  await expect(page.getByRole('region', { name: 'My questions' })).toContainText('Is a quieter waiting space available for my visit?')
})

test('documents: reviewed imports retain edited tasks, completion, source and stable identity', async ({ page }) => {
  await openSample(page)
  await expect(page.locator('#original-letter-panel')).toContainText('Cedar Family Practice')
  const initial = await review(page)
  await initial.getByRole('checkbox', { name: /Bring a photo ID/ }).uncheck()
  await initial.getByRole('button', { name: 'Confirm and add to my visit' }).click()
  let preparation = await showTasks(page)
  const count = await preparation.getByRole('checkbox').count()
  await expect(preparation.getByRole('checkbox', { name: 'Bring a photo ID, if I have one', exact: true })).toHaveCount(0)
  await preparation.getByRole('button', { name: 'Edit item: Bring my appointment letter', exact: true }).click()
  await preparation.getByRole('textbox', { name: 'Edit preparation item' }).fill('Put the appointment letter in my bag')
  await preparation.getByRole('button', { name: 'Save item' }).click()
  await preparation.getByRole('checkbox', { name: 'Put the appointment letter in my bag', exact: true }).check()
  await openSample(page)
  const repeated = await review(page)
  await repeated.getByRole('checkbox', { name: /Bring a photo ID/ }).uncheck()
  await repeated.getByRole('button', { name: 'Confirm and add to my visit' }).click()
  preparation = await showTasks(page)
  await expect(preparation.getByRole('checkbox')).toHaveCount(count)
  await expect(preparation.getByRole('checkbox', { name: 'Put the appointment letter in my bag', exact: true })).toBeChecked()
  await expect(preparation.getByRole('checkbox', { name: 'Bring my appointment letter', exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Visit documents' }).locator('.document-reference')).toHaveCount(1)
})

test('documents: conflicts require a choice and editing details keeps the original source intact', async ({ page }) => {
  await openSample(page)
  await confirm(page)
  await openSample(page, 'willow')
  let dialog = await review(page)
  await expect(dialog.getByRole('button', { name: 'Confirm and add to my visit' })).toBeDisabled()
  await dialog.getByRole('radio', { name: /^Keep current visit/ }).check()
  await dialog.getByRole('button', { name: 'Keep current visit', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Current visit', exact: true })).toContainText('Cedar Family Practice')
  await openSample(page, 'cedar', 'updated')
  dialog = await review(page)
  await dialog.getByRole('radio', { name: /^Use this letter/ }).check()
  await dialog.getByRole('button', { name: 'Confirm and add to my visit' }).click()
  await expect(page.getByRole('region', { name: 'Current visit', exact: true })).toContainText('10 December 2026')
  await route(page, 'letter')
  await page.getByRole('button', { name: 'Edit confirmed details', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Edit confirmed details', exact: true })
  await edit.getByRole('textbox', { name: 'Arrival instructions', exact: true }).fill('My own unchanged entrance note')
  await edit.getByRole('button', { name: 'Save visit details' }).click()
  await expect(page.getByRole('region', { name: 'Details in my visit plan' })).toContainText('My own unchanged entrance note')
  await expect(page.locator('#original-letter-panel')).not.toContainText('My own unchanged entrance note')
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('es')
  await expect(page.locator('html')).toHaveAttribute('lang', 'es')
  await expect(page.locator('#original-letter-panel')).toContainText('CARTA DE CITA DE EJEMPLO')
  await expect(page.locator('#original-letter-panel')).toContainText('10 de diciembre de 2026')
  await expect(page.getByRole('region', { name: 'Datos de mi plan de visita' })).toContainText('My own unchanged entrance note')
  await expect(page.getByRole('region', { name: 'Datos de mi plan de visita' })).toContainText('10 de diciembre de 2026')
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('en')
  await route(page, 'care')
  const sources = page.getByRole('region', { name: 'Visit documents' }).locator('.document-reference')
  await expect(sources).toHaveCount(2)
  await sources.first().getByRole('button', { name: 'Review sample letter' }).click()
  await expect(page.locator('#original-letter-panel')).toContainText('3 December 2026')
  await expect(page.locator('#original-letter-panel')).not.toContainText('10 December 2026')
})

test('documents: real filenames remain honest and mobile reading controls switch original and explanation', async ({ page }) => {
  await route(page, 'letter')
  await page.locator('input[type=file]').setInputFiles({ name: 'my-personal-letter.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4 sample upload bytes') })
  await expect(page.getByRole('region', { name: 'Selected file', exact: true })).toContainText('my-personal-letter.pdf')
  await expect(page.getByRole('region', { name: 'Selected file', exact: true })).toContainText('Document processing is not connected in this prototype. Try the sample appointment letter.')
  await expect(page.locator('#original-letter-panel')).toHaveCount(0)
  await openSample(page)
  await expect(page.getByRole('region', { name: 'Selected file', exact: true })).toContainText('It was not extracted from your selected file.')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('#explanation-panel')).toBeVisible()
  await expect(page.locator('#original-letter-panel')).toBeHidden()
  await page.getByRole('button', { name: 'Original sample', exact: true }).click()
  await expect(page.locator('#original-letter-panel')).toBeVisible()
  await expect(page.locator('#explanation-panel')).toBeHidden()
  await page.getByRole('button', { name: 'Explanation', exact: true }).click()
  await expect(page.locator('#explanation-panel')).toBeVisible()
  await page.getByRole('button', { name: 'Use larger document text' }).click()
  await expect(page.locator('.review-reader-grid')).toHaveClass(/review-large-text/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: 'artifacts/carenori-document-mobile.png', fullPage: true })
})

