import { expect, test, type Page } from '@playwright/test'

async function route(page: Page, value: string) {
  await page.evaluate(next => { window.location.hash = next }, value)
  await expect(page).toHaveURL(new RegExp(`#${value}$`))
}
async function openSample(page: Page, provider = 'cedar', variant = 'original') {
  await route(page, 'letter')
  await page.getByLabel('Sample clinic', { exact: true }).selectOption(provider)
  await page.getByLabel('Sample letter version', { exact: true }).selectOption(variant)
  await page.getByRole('button', { name: 'Open sample letter', exact: true }).click()
}
async function review(page: Page) {
  await page.getByRole('button', { name: 'Review and add to my visit', exact: true }).click()
  return page.getByRole('dialog', { name: 'Review appointment information', exact: true })
}
async function confirm(page: Page) {
  const dialog = await review(page)
  await dialog.getByRole('button', { name: 'Confirm and add to my visit', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'My care', exact: true, level: 1 })).toBeVisible()
}
async function showTasks(page: Page) {
  const show = page.getByRole('button', { name: /^View all \d+ preparation tasks$/ })
  if (await show.isVisible()) await show.click()
  return page.getByRole('region', { name: 'My preparation', exact: true })
}

