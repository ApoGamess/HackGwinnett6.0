import { expect, test } from '@playwright/test'
import { expectAccessible, expectNoOverflow } from './helpers'

test('complete connected CareNori visit from access preferences through selected print pack', async ({ page }) => {
  await page.addInitScript(() => {
    class SilentUtterance { text: string; lang = ''; rate = 1; voice = null; onend = null; onerror = null; constructor(text: string) { this.text = text } }
    Object.defineProperty(window, 'SpeechSynthesisUtterance', { configurable: true, value: SilentUtterance })
    const history: string[] = []
    Object.defineProperty(window, '__speechHistory', { value: history })
    Object.defineProperty(window, 'speechSynthesis', { configurable: true, value: { cancel() {}, getVoices: () => [{ lang: 'en-US', localService: true }], speak: (utterance: SpeechSynthesisUtterance) => history.push(utterance.text) } })
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Start my visit plan', exact: true }).click()
  await page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('link', { name: 'Preferences' }).click()
  await page.getByRole('checkbox', { name: 'Step-free access', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Written communication', exact: true }).check()
  await page.getByRole('button', { name: 'Return to My care', exact: true }).click()
  await page.getByRole('button', { name: 'Find a clinic', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Compare Willow Community Clinic', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Compare Cedar Family Practice', exact: true }).check()
  await expectAccessible(page)
  const cedar = page.locator('.provider-list article').filter({ has: page.getByRole('heading', { name: 'Cedar Family Practice', exact: true }) })
  await cedar.getByRole('button', { name: /Add this to my questions/ }).click()
  await cedar.getByRole('button', { name: 'Use this clinic in my visit plan', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Current visit', exact: true })).toContainText('No booking')
  await page.getByRole('button', { name: 'Review my appointment letter', exact: true }).click()
  await page.getByRole('button', { name: 'Open sample letter', exact: true }).click()
  await page.getByRole('button', { name: 'Review and add to my visit', exact: true }).click()
  await expectAccessible(page)
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm and add to my visit', exact: true }).click()
  await page.getByRole('button', { name: 'Choose and preview my access card', exact: true }).click()
  await page.getByRole('checkbox', { name: 'I prefer written communication.', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Please give me extra time to respond.', exact: true }).check()
  await page.getByRole('button', { name: 'Show in large text', exact: true }).click()
  await expectAccessible(page)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Open visit mode', exact: true }).click()
  const question = page.locator('.question-item').first()
  await question.getByRole('button', { name: /^Use question:/ }).click()
  const communication = page.getByRole('dialog', { name: 'Help me communicate', exact: true })
  await expect(communication.getByLabel('Your message', { exact: true })).toHaveValue('Is a quieter waiting space available for my visit?')
  expect(await page.evaluate(() => Reflect.get(window, '__speechHistory'))).toEqual([])
  await communication.getByRole('button', { name: 'Show message', exact: true }).click()
  await page.getByRole('dialog', { name: 'My message', exact: true }).getByRole('button', { name: 'Speak', exact: true }).click()
  expect(await page.evaluate(() => Reflect.get(window, '__speechHistory'))).toHaveLength(1)
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await question.getByRole('checkbox').check()
  if (await question.locator('details').getAttribute('open') === null) await question.locator('summary').click()
  await question.getByRole('textbox').fill('Ask reception again when I arrive.')
  await page.getByLabel('Optional typed notes', { exact: true }).fill('My own private visit note.')
  await page.getByRole('navigation', { name: 'Visit journey', exact: true }).getByRole('button', { name: 'After my visit', exact: true }).click()
  await page.getByLabel('Task title', { exact: true }).fill('Call to check the quiet waiting request')
  await page.getByLabel('Due date (optional)', { exact: true }).fill('2026-12-04')
  await page.getByRole('button', { name: 'Add follow-up task', exact: true }).click()
  await page.getByRole('button', { name: 'Prepare my visit summary', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Visit journey', exact: true }).getByRole('button', { name: 'After my visit', exact: true })).toHaveAttribute('aria-current', 'step')
  const preview = page.getByRole('article', { name: 'Visit summary preview', exact: true })
  await expect(preview).toContainText('Cedar Family Practice')
  await expect(preview).toContainText('Call to check the quiet waiting request')
  await expect(preview).not.toContainText('My own private visit note.')
  await expect(preview).not.toContainText('I prefer written communication.')
  await page.getByRole('checkbox', { name: 'Selected access statements', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Optional notes', exact: true }).check()
  await expect(preview).toContainText('My own private visit note.')
  await expect(preview).toContainText('I prefer written communication.')
  await expectAccessible(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await expectNoOverflow(page)
  await page.screenshot({ path: 'artifacts/carenori-prepared-summary.png', fullPage: true })
  await page.emulateMedia({ media: 'print' })
  await page.pdf({ path: 'artifacts/carenori-sample-visit-pack.pdf', format: 'A4', printBackground: true })
})



