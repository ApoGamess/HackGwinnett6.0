test('explicit public search preserves unknowns, dates, tags and separation; repeated searches use cache', async ({ page }) => {
  let queries = 0
  await page.route('https://overpass-api.de/api/interpreter?*', async route => { queries++; await route.fulfill({ json: publicFixture }) })
  await listOnly(page)
  await page.getByRole('button', { name: /Explore public places/ }).click()
  await page.getByRole('button', { name: 'List', exact: true }).click()
  expect(queries).toBe(0)
  await expect(page.locator('.place-result')).toHaveCount(1)
  await page.getByRole('button', { name: 'Search this area', exact: true }).click()
  await expect(page.locator('.place-result')).toHaveCount(2)
  expect(queries).toBe(1)
  await page.locator('.place-result').filter({ hasText: 'Public test clinic' }).click()
  await expect(page.locator('.place-detail')).toContainText('mapped area center, not an entrance')
  const wheelchair = page.locator('.feature-records > li').filter({ has: page.getByText('Wheelchair access', { exact: true }) })
  await expect(wheelchair).toContainText('Unknown')
  await expect(page.locator('.place-detail > .source-details')).toContainText('2025-04-12')
  await expect(page.locator('.place-detail > .source-details')).toContainText('No inspection date provided')
  await expect(page.locator('.place-detail')).toContainText('narrow side door')
  await page.getByRole('button', { name: 'Search this area', exact: true }).click()
  await expect(page.getByText('Public records loaded from the short-lived cache.')).toBeVisible()
  expect(queries).toBe(1)
  await expect(page.locator('.place-result')).toHaveCount(2)
  await page.locator('.place-result').filter({ hasText: 'Public test entrance' }).click()
  await expect(page.locator('.place-detail > .source-details')).toContainText('2023-02-01')
  await expect(page.locator('.feature-records')).toContainText('Limited')
  await expect(page.locator('.place-results')).not.toContainText('Fictional demo')
  await page.getByRole('button', { name: /Try the demo campus/ }).click()
  await page.getByRole('button', { name: 'List', exact: true }).click()
  await expect(page.locator('.place-results')).not.toContainText('Public test clinic')
})

